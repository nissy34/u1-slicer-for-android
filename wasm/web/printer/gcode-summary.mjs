// Reads what the print-configuration screen shows from an Orca/Snapmaker
// G-code file: per-filament grams (`; filament used [g] = …`), materials,
// colours, estimated time, nozzle diameter, layers and the tools the body
// actually uses — and builds the Map & Print tool remap from the user's
// filament → tool-head choices. Mirrored by test/printer-gcode-summary.test.mjs.

const listOf = (v, sep) => String(v).split(sep).map((s) => s.trim()).filter((s) => s.length);

/** "1d 2h 3m 4s" / "34m 35s" → seconds (null if unparseable). */
export function parseDurationText(text) {
  const t = String(text ?? '').trim();
  if (!t) return null;
  let total = 0, any = false;
  for (const [, n, u] of t.matchAll(/(\d+(?:\.\d+)?)\s*([dhms])/g)) {
    any = true;
    total += Number(n) * { d: 86400, h: 3600, m: 60, s: 1 }[u];
  }
  return any ? Math.round(total) : null;
}

/**
 * Parse the summary out of G-code text. Comment keys come in two spellings:
 * "; key = value" in the config footer and "; key: value" in the header block.
 */
export function summarizeGcode(text) {
  const kv = new Map();
  const tools = new Set();
  let firstTool = null;
  const re = /^(?:;\s*([^=:\n]+?)\s*[=:]\s*(.*?)\s*|T(\d+)\s*(?:;.*)?)$/gm;
  for (const m of String(text).matchAll(re)) {
    if (m[3] != null) {
      const t = Number(m[3]);
      tools.add(t);
      if (firstTool == null) firstTool = t;
    } else if (!kv.has(m[1])) {
      kv.set(m[1], m[2]);
    }
  }
  const nums = (k) => (kv.has(k) ? listOf(kv.get(k), ',').map(Number).filter(Number.isFinite) : []);
  const grams = nums('filament used [g]');
  const mm = nums('filament used [mm]');
  const types = kv.has('filament_type') ? listOf(kv.get('filament_type'), ';') : [];
  const colours = kv.has('filament_colour') ? listOf(kv.get('filament_colour'), ';')
    : kv.has('extruder_colour') ? listOf(kv.get('extruder_colour'), ';') : [];
  const nozzle = nums('nozzle_diameter');
  const time = parseDurationText(kv.get('estimated printing time (normal mode)') ?? kv.get('model printing time'));
  const totalG = Number(kv.get('total filament used [g]'));
  const layers = Number(kv.get('total layer number') ?? kv.get('total layers count'));
  const count = Math.max(grams.length, types.length, colours.length, 0);
  const filaments = Array.from({ length: count }, (_, i) => ({
    index: i,
    grams: grams[i] ?? 0,
    mm: mm[i] ?? 0,
    material: types[i] ?? types[0] ?? 'PLA',
    color: /^#[0-9a-fA-F]{6}/.test(colours[i] ?? '') ? colours[i].slice(0, 7).toUpperCase() : null,
  }));
  return {
    filaments,
    toolsUsed: [...tools].sort((a, b) => a - b),
    firstTool,
    estimatedSeconds: time,
    totalGrams: Number.isFinite(totalG) ? totalG : grams.reduce((a, b) => a + b, 0),
    nozzleDiameter: nozzle[0] ?? null,
    layers: Number.isFinite(layers) ? layers : null,
    generator: (String(text).match(/^; generated by (.+?)(?: on .*)?$/m) ?? [])[1] ?? null,
  };
}

/**
 * One card per tool the G-code prints with. `toolMap[i]` is the tool that file
 * filament i currently prints with (the slicer's colour → extruder mapping;
 * identity for a plain Orca file). Filaments sharing a tool share a card
 * (grams summed), so the remap stays a function of the current tool.
 */
export function buildFilamentCards(summary, toolMap = null) {
  toolMap ??= inferToolMap(summary);
  const toolOf = (i) => (toolMap && Number.isInteger(toolMap[i]) ? toolMap[i] : i);
  const used = new Set(summary.toolsUsed);
  const cards = new Map();
  summary.filaments.forEach((f) => {
    const tool = toolOf(f.index);
    // Skip filaments that never print (0 g and their tool never selected).
    if (!(f.grams > 0) && !used.has(tool)) return;
    const c = cards.get(tool) ?? { tool, filaments: [], grams: 0, material: f.material, color: f.color };
    c.filaments.push(f.index);
    c.grams += f.grams;
    c.color ??= f.color;
    cards.set(tool, c);
  });
  // Tools used in the body with no footer data (hand-written / foreign G-code).
  for (const t of used) if (!cards.has(t)) cards.set(t, { tool: t, filaments: [], grams: 0, material: summary.filaments[0]?.material ?? 'PLA', color: null });
  return [...cards.values()].sort((a, b) => a.tool - b.tool);
}

/**
 * Without the slicer's mapping, assume filament i prints with T<i> — unless the
 * body was already remapped (e.g. the Android app's Map & Print export, where
 * filament 0 prints with T2): then pair the printing filaments with the used
 * tools in order, which is how an ordered colour → slot remap leaves them.
 */
export function inferToolMap(summary) {
  const used = summary.toolsUsed;
  const printing = summary.filaments.filter((f) => f.grams > 0).map((f) => f.index);
  if (printing.every((i) => used.includes(i)) || printing.length !== used.length) return null;
  const map = summary.filaments.map((f) => f.index);
  printing.forEach((fi, k) => { map[fi] = used[k]; });
  return map;
}

/**
 * targetSlots for remapGcode(): index = tool in the G-code now, value = chosen
 * tool head (0-based). Unlisted tools keep their index. Identity → [].
 */
export function buildPrintRemap(cards, heads) {
  const max = Math.max(-1, ...cards.map((c) => c.tool));
  const target = Array.from({ length: max + 1 }, (_, i) => i);
  cards.forEach((c, k) => { if (Number.isInteger(heads[k])) target[c.tool] = heads[k]; });
  return target.every((s, i) => s === i) ? [] : target;
}

/** Cards whose head carries a different material than the G-code was sliced for (B118's warning). */
export function materialMismatches(cards, heads, slots) {
  return cards.map((c, k) => {
    const slot = slots.find((s) => s.index === heads[k]);
    return slot && slot.materialType && c.material && slot.materialType.toUpperCase() !== c.material.toUpperCase()
      ? `Sliced as ${c.material} but E${heads[k] + 1} has ${slot.materialType}` : null;
  });
}

/** Two cards on one head print in the same filament — legal, but worth a note. */
export function sharedHeads(heads) {
  const seen = new Map();
  heads.forEach((h, k) => seen.set(h, [...(seen.get(h) ?? []), k]));
  return [...seen.entries()].filter(([, ks]) => ks.length > 1).map(([h]) => h);
}

/**
 * The largest embedded thumbnail ("; thumbnail begin WxH LEN" … "; thumbnail end",
 * also Orca's "; thumbnail_PNG begin") as a data: URL, or null. Only looks at
 * the head of the file, where slicers put them.
 */
export function extractThumbnail(text, maxScan = 2 * 2 ** 20) {
  const head = String(text).slice(0, maxScan);
  let best = null;
  const re = /^; thumbnail(?:_(PNG|JPG|QOI))? begin (\d+)x(\d+)[^\n]*\n([\s\S]*?)^; thumbnail(?:_\w+)? end/gm;
  for (const m of head.matchAll(re)) {
    const fmt = (m[1] ?? 'PNG').toUpperCase();
    if (fmt === 'QOI') continue;
    const area = Number(m[2]) * Number(m[3]);
    if (best && best.area >= area) continue;
    const b64 = m[4].split('\n').map((l) => l.replace(/^;\s?/, '').trim()).join('');
    if (/^[A-Za-z0-9+/=]+$/.test(b64)) best = { area, url: `data:image/${fmt === 'JPG' ? 'jpeg' : 'png'};base64,${b64}` };
  }
  return best?.url ?? null;
}
