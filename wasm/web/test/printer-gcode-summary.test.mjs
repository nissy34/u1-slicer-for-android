// Print-configuration screen: G-code footer parsing and the Map & Print remap
// (the remap itself is gcode-tool-remap.js, held to GcodeToolRemapperTest).
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import test from 'node:test';
import {
  buildFilamentCards, buildPrintRemap, materialMismatches, parseDurationText, sharedHeads, summarizeGcode,
} from '../printer/gcode-summary.mjs';

const require = createRequire(import.meta.url);
const { remapGcode } = require('../gcode-tool-remap.js');

const GCODE = `; HEADER_BLOCK_START
; generated by Snapmaker Orca 2.2.4 on 2026-05-02 at 19:23:22
; total layer number: 28
; HEADER_BLOCK_END
PRINT_START
T0
SM_PRINT_AUTO_FEED EXTRUDER=0
SM_PRINT_AUTO_FEED EXTRUDER=1
M104 S220 T1
G1 X1 Y1 E1
T1
G1 X2 Y2 E1
T0
; filament used [mm] = 1207.26, 3022.77
; filament used [g] = 3.60, 9.02
; total filament used [g] = 12.62
; estimated printing time (normal mode) = 34m 35s
; filament_colour = #FFFFFF;#000000
; filament_type = PLA;PETG
; nozzle_diameter = 0.4,0.4,0.4,0.4
`;

test('duration text parses Orca formats', () => {
  assert.equal(parseDurationText('34m 35s'), 2075);
  assert.equal(parseDurationText('1d 2h 3m 4s'), 93784);
  assert.equal(parseDurationText(''), null);
});

test('summary reads grams, materials, colours, time, nozzle, layers, tools', () => {
  const s = summarizeGcode(GCODE);
  assert.deepEqual(s.filaments.map((f) => [f.grams, f.material, f.color]), [[3.6, 'PLA', '#FFFFFF'], [9.02, 'PETG', '#000000']]);
  assert.equal(s.totalGrams, 12.62);
  assert.equal(s.estimatedSeconds, 2075);
  assert.equal(s.nozzleDiameter, 0.4);
  assert.equal(s.layers, 28);
  assert.deepEqual(s.toolsUsed, [0, 1]);
  assert.equal(s.firstTool, 0);
  assert.equal(s.generator, 'Snapmaker Orca 2.2.4');
});

test('real Orca G-code from the repo parses', () => {
  const s = summarizeGcode(readFileSync(new URL('../../../docs/issue-evidence/issue-116/outputcookie.gcode', import.meta.url), 'utf8'));
  // An Android Map & Print export: 2 filaments padded to 4, body remapped to T2/T3.
  assert.deepEqual(s.filaments.map((f) => f.grams), [3.6, 9.02, 0, 0]);
  assert.deepEqual(s.filaments.map((f) => f.material), ['PLA', 'PETG', 'PETG', 'PETG']);
  assert.equal(s.estimatedSeconds, 34 * 60 + 35);
  assert.deepEqual(s.toolsUsed, [2, 3]);
  // Already-remapped body: printing filaments pair with the used tools in order.
  assert.deepEqual(buildFilamentCards(s).map((c) => [c.tool, c.grams, c.material]), [[2, 3.6, 'PLA'], [3, 9.02, 'PETG']]);
});

test('cards: one per tool, identity without a slicer mapping', () => {
  const cards = buildFilamentCards(summarizeGcode(GCODE));
  assert.deepEqual(cards.map((c) => [c.tool, c.grams, c.material]), [[0, 3.6, 'PLA'], [1, 9.02, 'PETG']]);
});

test('cards follow the slicer colour→extruder mapping and merge shared tools', () => {
  // Slicer mapped colour 0 → E3 and colour 1 → E3: the body only uses T2.
  const g = GCODE.replace(/^T[01]$/gm, 'T2').replace('M104 S220 T1', 'M104 S220 T2');
  const cards = buildFilamentCards(summarizeGcode(g), [2, 2]);
  assert.equal(cards.length, 1);
  assert.equal(cards[0].tool, 2);
  assert.deepEqual(cards[0].filaments, [0, 1]);
  assert.ok(Math.abs(cards[0].grams - 12.62) < 1e-9);
});

test('unused zero-gram filament gets no card', () => {
  const g = GCODE.replace('; filament used [g] = 3.60, 9.02', '; filament used [g] = 3.60, 9.02, 0.00')
    .replace('; filament_type = PLA;PETG', '; filament_type = PLA;PETG;PLA');
  assert.equal(buildFilamentCards(summarizeGcode(g)).length, 2);
});

test('print remap: identity is empty; chosen heads rewrite tools via the app remapper', () => {
  const cards = buildFilamentCards(summarizeGcode(GCODE));
  assert.deepEqual(buildPrintRemap(cards, [0, 1]), []);
  const target = buildPrintRemap(cards, [3, 2]);
  assert.deepEqual(target, [3, 2]);
  const out = remapGcode(GCODE, target).split('\n');
  assert.ok(out.includes('T3') && out.includes('T2'));
  assert.ok(!out.includes('T0') && !out.includes('T1'));
  assert.ok(out.includes('SM_PRINT_AUTO_FEED EXTRUDER=3'));
  assert.ok(out.includes('M104 S220 T2'));
});

test('print remap keeps unlisted tools and extends to higher heads', () => {
  const cards = [{ tool: 1, filaments: [1], grams: 1, material: 'PLA', color: null }];
  assert.deepEqual(buildPrintRemap(cards, [3]), [0, 3]);
});

test('material mismatch and shared-head notes', () => {
  const cards = buildFilamentCards(summarizeGcode(GCODE));
  const slots = [0, 1, 2, 3].map((i) => ({ index: i, materialType: i === 1 ? 'PETG' : 'PLA' }));
  assert.deepEqual(materialMismatches(cards, [0, 1], slots), [null, null]);
  assert.deepEqual(materialMismatches(cards, [1, 0], slots), ['Sliced as PLA but E2 has PETG', 'Sliced as PETG but E1 has PLA']);
  assert.deepEqual(sharedHeads([2, 2, 1]), [2]);
});

test('largest PNG thumbnail is extracted as a data URL', async () => {
  const { extractThumbnail } = await import('../printer/gcode-summary.mjs');
  const g = '; thumbnail begin 16x16 8\n; AAAA\n; BBBB\n; thumbnail end\n; thumbnail begin 300x300 8\n; CCCC\n; DDDD\n; thumbnail end\nG28\n';
  assert.equal(extractThumbnail(g), 'data:image/png;base64,CCCCDDDD');
  assert.equal(extractThumbnail('G28\n'), null);
  const real = readFileSync(new URL('../../../docs/issue-evidence/issue-116/outputcookie.gcode', import.meta.url), 'utf8');
  assert.match(extractThumbnail(real), /^data:image\/png;base64,iVBOR/);
});
