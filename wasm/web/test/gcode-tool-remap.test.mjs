// Mirrors app/src/test/java/com/u1/slicer/gcode/GcodeToolRemapperTest.kt case
// by case, so the JS port is held to the same contract as the app.
//   cd wasm/web && npm test
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import test from 'node:test';

const require = createRequire(import.meta.url);
const { remapLine, remapGcode } = require('../gcode-tool-remap.js');
const { lacksToolChanges, hasToolChanges } = {
  lacksToolChanges: (g, ...t) => t.every((x) => !g.split('\n').some((l) => l.trim() === x)),
  hasToolChanges: (g, ...t) => t.every((x) => g.split('\n').some((l) => l.trim() === x)),
};

const identity = new Map([[0, 0], [1, 1]]);
const shift2 = new Map([[0, 2], [1, 3]]); // E3+E4 scenario

test('standalone T0 remapped to T2', () => assert.equal(remapLine('T0', shift2), 'T2'));
test('standalone T1 remapped to T3', () => assert.equal(remapLine('T1', shift2), 'T3'));
test('standalone T0 with comment remapped', () => assert.equal(remapLine('T0 ; change tool', shift2), 'T2'));
test('standalone T with identity map unchanged', () => assert.equal(remapLine('T0', identity), 'T0'));
test('unknown compact index left unchanged', () => assert.equal(remapLine('T5', shift2), 'T5'));
test('M104 T0 remapped', () => assert.equal(remapLine('M104 S210 T0', shift2), 'M104 S210 T2'));
test('M109 T1 remapped', () => assert.equal(remapLine('M109 S210 T1', shift2), 'M109 S210 T3'));
test('M104 T0 with leading T param remapped', () => assert.equal(remapLine('M104 T0 S210', shift2), 'M104 T2 S210'));

test('bambu ams commands remap filament indices but not sentinel slots', () => {
  const compact = new Map([[1, 0]]);
  assert.equal(remapLine('M620 S1A', compact), 'M620 S0A');
  assert.equal(remapLine('M621 S1A', compact), 'M621 S0A');
  assert.equal(remapLine('M620.11 S1 I1 E-18 F1200', compact), 'M620.11 S1 I0 E-18 F1200');
  assert.equal(remapLine('M620 S255A', compact), 'M620 S255A');
});

test('unrelated line not modified', () => {
  const line = 'G1 X10 Y20 E1.5 F3000';
  assert.equal(remapLine(line, shift2), line);
});
test('G28 home not modified', () => assert.equal(remapLine('G28 ; home', shift2), 'G28 ; home'));

test('remap file rewrites tool changes and temperatures', () => {
  const gcode = ['; generated by Snapmaker Orca', 'G28', 'M104 S210 T0', 'T0', 'G1 X0 Y0', 'M109 S210 T0', 'T1', 'M104 S215 T1'].join('\n');
  const lines = remapGcode(gcode, [2, 3]).split('\n');
  assert.deepEqual(lines.slice(0, 8), ['; generated by Snapmaker Orca', 'G28', 'M104 S210 T2', 'T2', 'G1 X0 Y0', 'M109 S210 T2', 'T3', 'M104 S215 T3']);
});

test('remap leaves no trace of original compact tool indices', () => {
  const result = remapGcode('T0\nT1\nM104 S210 T0\nM109 S215 T1\nG1 X0\n', [2, 3]);
  assert.ok(lacksToolChanges(result, 'T0', 'T1'));
  assert.ok(hasToolChanges(result, 'T2', 'T3'));
});

test('remap with identity mapping produces correct output', () => {
  const result = remapGcode('T0\nT1\nM104 S210 T0\n', [0, 1]);
  assert.ok(result.includes('T0'));
  assert.ok(result.includes('T1'));
  assert.ok(!result.includes('T2'));
});

test('SM_PRINT_AUTO_FEED EXTRUDER remapped', () => {
  assert.equal(remapLine('SM_PRINT_AUTO_FEED EXTRUDER=0', shift2), 'SM_PRINT_AUTO_FEED EXTRUDER=2');
  assert.equal(remapLine('SM_PRINT_AUTO_FEED EXTRUDER=1', shift2), 'SM_PRINT_AUTO_FEED EXTRUDER=3');
});
test('SM_PRINT_FLOW_CALIBRATE INDEX remapped', () =>
  assert.equal(remapLine('SM_PRINT_FLOW_CALIBRATE INDEX=0 TARGET_TEMP=210', shift2), 'SM_PRINT_FLOW_CALIBRATE INDEX=2 TARGET_TEMP=210'));
test('SM_PRINT_START_LINE INDEX remapped', () =>
  assert.equal(remapLine('SM_PRINT_START_LINE INDEX=1 TARGET_TEMP=210', shift2), 'SM_PRINT_START_LINE INDEX=3 TARGET_TEMP=210'));
test('SM commands not remapped with identity map', () =>
  assert.equal(remapLine('SM_PRINT_AUTO_FEED EXTRUDER=0', identity), 'SM_PRINT_AUTO_FEED EXTRUDER=0'));
test('non-SM line with EXTRUDER= is not remapped', () =>
  assert.equal(remapLine('BED_MESH_CALIBRATE EXTRUDER=0', shift2), 'BED_MESH_CALIBRATE EXTRUDER=0'));

test('full file remap includes SM commands', () => {
  const gcode = ['T0', 'SM_PRINT_AUTO_FEED EXTRUDER=0', 'SM_PRINT_AUTO_FEED EXTRUDER=1',
    'SM_PRINT_FLOW_CALIBRATE INDEX=0 TARGET_TEMP=210', 'SM_PRINT_FLOW_CALIBRATE INDEX=1 TARGET_TEMP=210',
    'SM_PRINT_START_LINE INDEX=1 TARGET_TEMP=210', 'G1 X0 Y0', 'M104 S210 T0'].join('\n');
  const lines = remapGcode(gcode, [2, 3]).split('\n');
  assert.deepEqual(lines.slice(0, 8), ['T2', 'SM_PRINT_AUTO_FEED EXTRUDER=2', 'SM_PRINT_AUTO_FEED EXTRUDER=3',
    'SM_PRINT_FLOW_CALIBRATE INDEX=2 TARGET_TEMP=210', 'SM_PRINT_FLOW_CALIBRATE INDEX=3 TARGET_TEMP=210',
    'SM_PRINT_START_LINE INDEX=3 TARGET_TEMP=210', 'G1 X0 Y0', 'M104 S210 T2']);
});
