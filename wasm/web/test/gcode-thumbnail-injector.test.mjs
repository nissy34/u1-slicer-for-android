// Mirrors app/src/androidTest/java/com/u1/slicer/gcode/GcodeThumbnailInjectorTest.kt
// (instrumented on Android) case by case, as Node tests on the same asset and the
// pure-JS image codec. Files become bytes / G-code text; inject() returns the new
// G-code text or null instead of rewriting a file and returning true/false.
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import test from 'node:test';
import { GcodeThumbnailInjector as G, pureJsImageCodec } from '../pipeline/gcode-thumbnail-injector.mjs';

const ASSET = new URL('../../../app/src/androidTest/assets/u1-auxiliary-fan-cover-hex_mw.3mf', import.meta.url);
const threeMf = new Uint8Array(readFileSync(ASSET));
const codec = pureJsImageCodec;
const opts = { imageCodec: codec };

test('extractPreviewImage_returns_bitmap_from_3mf', async () => {
  const bitmap = await G.extractPreviewImage(threeMf, null, codec);
  assert.notEqual(bitmap, null, 'Should extract a preview image from 3MF');
  assert.ok(bitmap.width > 0, 'Bitmap width > 0');
  assert.ok(bitmap.height > 0, 'Bitmap height > 0');
});

test('extractPreviewImage_returns_null_for_non_3mf', async () => {
  const bitmap = await G.extractPreviewImage(new TextEncoder().encode('hello'), null, codec);
  assert.equal(bitmap, null, 'Non-ZIP file should return null');
});

test('buildThumbnailBlocks_contains_both_sizes', async () => {
  const bitmap = await G.extractPreviewImage(threeMf, null, codec);
  const blocks = await G.buildThumbnailBlocks(bitmap, codec);
  assert.ok(blocks.includes('; thumbnail begin 48x48'), 'Should contain 48x48 thumbnail');
  assert.ok(blocks.includes('; thumbnail begin 300x300'), 'Should contain 300x300 thumbnail');
  assert.ok(blocks.includes('; thumbnail end'), 'Should contain thumbnail end markers');
  assert.ok(!blocks.includes('; THUMBNAIL_BLOCK_START'), 'Should NOT contain THUMBNAIL_BLOCK_START wrappers');
  assert.equal([...blocks.matchAll(/; thumbnail begin/g)].length, 2, 'Should have 2 thumbnail begin markers');
  assert.equal([...blocks.matchAll(/; thumbnail end/g)].length, 2, 'Should have 2 thumbnail end markers');
});

test('buildThumbnailBlocks_lines_are_commented', async () => {
  const bitmap = await G.extractPreviewImage(threeMf, null, codec);
  const blocks = await G.buildThumbnailBlocks(bitmap, codec);
  for (const line of blocks.split(/\r\n|\r|\n/)) {
    if (line.length > 0) assert.ok(line === ';' || line.startsWith('; '), `Every line should start with ';' or '; ': ${line}`);
  }
});

test('inject_inserts_after_header_block_end', async () => {
  const gcode = '; generated by test\n; HEADER_BLOCK_END\nG28\nG1 X10 Y10\n';
  const content = await G.inject(gcode, threeMf, 'fan-cover.3mf', opts);
  assert.notEqual(content, null, 'inject() should return true');
  const headerEndPos = content.indexOf('; HEADER_BLOCK_END');
  const thumbnailPos = content.indexOf('; thumbnail begin');
  const g28Pos = content.indexOf('G28');
  assert.ok(thumbnailPos >= 0, 'Thumbnail should exist');
  assert.ok(thumbnailPos > headerEndPos, 'Thumbnail should be after HEADER_BLOCK_END');
  assert.ok(thumbnailPos < g28Pos, 'Thumbnail should be before G28');
});

test('inject_prepends_when_no_header_block_end', async () => {
  const content = await G.inject('G28\nG1 X10 Y10\n', threeMf, 'fan-cover.3mf', opts);
  assert.notEqual(content, null, 'inject() should return true');
  assert.ok(content.startsWith('; thumbnail begin 48x48'), 'Should start with thumbnail begin (no wrapper)');
  assert.ok(content.includes('; thumbnail begin 300x300'), 'Should contain 300x300 thumbnail');
});

test('inject_returns_false_for_non_3mf_source', async () => {
  const stl = new TextEncoder().encode('solid test\nendsolid test\n');
  const result = await G.inject('G28\n', stl, 'model.stl', opts);
  assert.equal(result, null, 'inject() should return false for .stl source');
});

test('inject_returns_false_for_missing_source', async () => {
  const result = await G.inject('G28\n', null, '/nonexistent/model.3mf', opts);
  assert.equal(result, null, 'inject() should return false for missing source');
});
