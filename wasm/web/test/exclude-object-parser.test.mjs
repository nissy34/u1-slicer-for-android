import assert from 'node:assert/strict';
import test from 'node:test';
import { parseExcludeObjects } from '../pipeline/exclude-object-parser.mjs';

const parseLines = (...lines) => parseExcludeObjects(lines.join('\n'));
const near = (exp, act, d) => assert.ok(Math.abs(exp - act) <= d, `expected ${exp} got ${act}`);

test('parses name center and polygon from single define line', () => {
  const result = parseLines(
    'EXCLUDE_OBJECT_DEFINE NAME=cube_1 CENTER=100.0,50.0 POLYGON=[[80.0,30.0],[120.0,30.0],[120.0,70.0],[80.0,70.0]]',
  );
  assert.equal(result.length, 1);
  assert.equal(result[0].name, 'cube_1');
  near(100.0, result[0].center[0], 0.01);
  near(50.0, result[0].center[1], 0.01);
  assert.equal(result[0].polygon.length, 4);
  near(80.0, result[0].polygon[0][0], 0.01);
  near(30.0, result[0].polygon[0][1], 0.01);
});

test('handles missing polygon gracefully returns empty polygon list', () => {
  const result = parseLines('EXCLUDE_OBJECT_DEFINE NAME=obj_1 CENTER=135.0,135.0');
  assert.equal(result.length, 1);
  assert.equal(result[0].name, 'obj_1');
  near(135.0, result[0].center[0], 0.01);
  assert.ok(result[0].polygon.length === 0);
});

test('parses multiple define lines in order', () => {
  const result = parseLines(
    'EXCLUDE_OBJECT_DEFINE NAME=obj_a CENTER=50.0,50.0 POLYGON=[[40.0,40.0],[60.0,40.0],[60.0,60.0],[40.0,60.0]]',
    'EXCLUDE_OBJECT_DEFINE NAME=obj_b CENTER=200.0,200.0 POLYGON=[[190.0,190.0],[210.0,190.0],[210.0,210.0],[190.0,210.0]]',
  );
  assert.equal(result.length, 2);
  assert.equal(result[0].name, 'obj_a');
  assert.equal(result[1].name, 'obj_b');
});

test('returns empty list when no define lines present', () => {
  const result = parseLines('; generated by OrcaSlicer', 'G28 ; home all axes', 'G1 X100 Y100 F3000');
  assert.ok(result.length === 0);
});

test('ignores EXCLUDE_OBJECT_START and EXCLUDE_OBJECT_END lines', () => {
  const result = parseLines(
    'EXCLUDE_OBJECT_START NAME=cube_1',
    'EXCLUDE_OBJECT_DEFINE NAME=cube_1 CENTER=100.0,100.0',
    'EXCLUDE_OBJECT_END NAME=cube_1',
  );
  assert.equal(result.length, 1);
  assert.equal(result[0].name, 'cube_1');
});
