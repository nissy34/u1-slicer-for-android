#!/usr/bin/env node
// End-to-end test of the Printer tab against the MOCK Moonraker
// (test/mock-moonraker.mjs) in headless Chromium. Never point this at a real
// printer: it starts, pauses, resumes and cancels prints.
//
//   node wasm/web/printer-e2e.mjs [screenshot-dir] [--model path/to/model.stl]
//
// With --model (needs the built engine) it also slices the model in the Slicer
// tab and prints the result through the print-configuration screen.
import { execSync, spawn } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { startMockMoonraker } from './test/mock-moonraker.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const args = process.argv.slice(2);
const mi = args.indexOf('--model');
const model = mi >= 0 ? resolve(args.splice(mi, 2)[1]) : null;
const shots = resolve(args[0] ?? join(here, '../build/printer-e2e'));
mkdirSync(shots, { recursive: true });

const require = createRequire(import.meta.url);
let playwright;
try { playwright = require('playwright'); } catch { playwright = require(join(execSync('npm root -g').toString().trim(), 'playwright')); }

const KEY = 'e2e-key';
const mock = await startMockMoonraker({ apiKey: KEY, tickMs: 300 });
const strict = await startMockMoonraker({ cors: ['http://not-this-page.example'] });
const noWs = await startMockMoonraker({ websocket: false });
const port = 8000 + Math.floor(Math.random() * 1000);
const server = spawn(process.execPath, [join(here, 'serve.mjs'), String(port)], { stdio: ['ignore', 'pipe', 'inherit'] });
await new Promise((ok) => server.stdout.once('data', ok));
const base = `http://localhost:${port}/`;

const GCODE = `; HEADER_BLOCK_START
; generated by Snapmaker Orca 2.2.4 on 2026-10-16 at 12:00:00
; total layer number: 50
; HEADER_BLOCK_END
PRINT_START
T0
SM_PRINT_AUTO_FEED EXTRUDER=0
SM_PRINT_AUTO_FEED EXTRUDER=1
M104 S220 T0
G1 X10 Y10 E1
T1
M109 S235 T1
G1 X20 Y20 E1
T0
PRINT_END
; filament used [mm] = 1207.26, 3022.77
; filament used [g] = 3.60, 9.02
; total filament used [g] = 12.62
; estimated printing time (normal mode) = 34m 35s
; filament_colour = #FFFFFF;#000000
; filament_type = PLA;PETG
; nozzle_diameter = 0.4,0.4,0.4,0.4
`;
const gcodePath = join(tmpdir(), `u1-e2e-${process.pid}.gcode`);
writeFileSync(gcodePath, GCODE);

let failures = 0;
const check = (cond, msg) => { console.log(`${cond ? 'ok  ' : 'FAIL'} ${msg}`); if (!cond) failures++; };
const reqs = () => fetch(`${mock.url}/__mock/requests`).then((r) => r.json());
const clearReqs = () => fetch(`${mock.url}/__mock/requests`, { method: 'DELETE' });
const mockState = () => fetch(`${mock.url}/__mock/state`).then((r) => r.json());

const browser = await playwright.chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
try {
  const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
  const page = await ctx.newPage();
  const errors = [];
  page.on('pageerror', (e) => { errors.push(e.message); console.error('pageerror:', e.message); });
  page.on('dialog', (d) => { errors.push(`unexpected native dialog: ${d.message()}`); d.dismiss(); });
  await page.goto(`${base}#printer`);
  await page.waitForSelector('#printerView:not([hidden])');
  check(await page.evaluate(() => getComputedStyle(document.querySelector('.layout')).display === 'none'), 'slicer view hidden on the Printer tab');
  const text = (sel) => page.textContent(sel).then((t) => t.replace(/\s+/g, ' ').trim());

  // ---- CORS rejection is explained ----------------------------------------------------------------
  await page.fill('#pUrl', strict.url.replace('http://', ''));
  await page.click('#pConnect');
  await page.waitForFunction(() => document.getElementById('pConnStatus').classList.contains('error'));
  check((await text('#pConnStatus')).includes('cors_domains'), 'blocked origin → cors_domains explanation');

  // ---- API key required ----------------------------------------------------------------------------
  await page.fill('#pUrl', mock.url.replace('http://', ''));
  await page.fill('#pKey', '');
  await page.click('#pConnect');
  await page.waitForFunction(() => /authentication required/.test(document.getElementById('pConnStatus').textContent));
  check(true, 'missing API key → "authentication required"');

  // ---- connect + live status -------------------------------------------------------------------------
  await page.fill('#pKey', KEY);
  await page.dispatchEvent('#pKey', 'change');
  await clearReqs();
  await page.click('#pConnect');
  await page.waitForFunction(() => document.getElementById('pBadge').textContent === 'STANDBY', null, { timeout: 15000 });
  await page.waitForFunction(() => document.querySelector('#pMode span').textContent === 'live', null, { timeout: 10000 });
  check(true, 'connected; badge STANDBY; live websocket');
  check((await reqs()).some((x) => x.method === 'UPGRADE' && x.query.token), 'websocket authenticated with a oneshot token');
  check((await text('#pConnStatus')).includes('U1-mock'), 'printer hostname shown');
  check((await text('#pTemps')).includes('Bed'), 'temperatures shown');

  // ---- camera --------------------------------------------------------------------------------------------
  await page.waitForFunction(() => { const i = document.getElementById('pCamImg'); return i.src.startsWith('blob:') && i.naturalWidth > 0; }, null, { timeout: 10000 });
  check(true, 'camera snapshot frames render (blob URL, CORS fetch with key)');
  await page.waitForFunction(() => getComputedStyle(document.getElementById('pCamHint')).display === 'none');
  check(true, 'camera hint hidden once frames arrive');
  await page.waitForTimeout(2300);
  let r = await reqs();
  check(r.some((x) => x.method === 'WS' && x.path === 'camera.start_monitor'), 'camera keepalive (camera.start_monitor) sent');
  await page.selectOption('#pCamMode', 'stream');
  await page.waitForFunction(() => { const i = document.getElementById('pCamImg'); return i.src.includes('action=stream') && i.naturalWidth > 0; }, null, { timeout: 10000 });
  check(true, 'MJPEG stream renders (crossorigin=anonymous)');
  await page.selectOption('#pCamMode', 'snapshot');

  // ---- LED (no confirm: light only) ------------------------------------------------------------------------
  await clearReqs();
  await page.click('#pLed');
  await page.waitForFunction(() => document.getElementById('pLed').textContent === 'Light: on');
  r = await reqs();
  check(r.some((x) => x.path === '/printer/gcode/script' && x.json?.script === 'SET_LED LED=cavity_led WHITE=1.0 RED=0 GREEN=0 BLUE=0'), 'LED toggle sends SET_LED');

  // ---- sync filaments (RFID) ---------------------------------------------------------------------------------
  await page.click('#pSync');
  await page.waitForSelector('#syApply', { timeout: 15000 });
  check((await text('#pDialog')).includes('Matched: Prusament'), 'sync preview matches E1 against the library');
  await page.click('#syApply');
  await page.waitForFunction(() => document.querySelector('[data-slot="0"]').textContent.includes('Prusament'));
  const e2 = await text('[data-slot="1"]');
  check(e2.includes('PETG') && e2.includes('#E72F1D'), 'E2 synced to PETG #E72F1D');

  // ---- slot editor + library picker ----------------------------------------------------------------------------
  await page.click('[data-edit="3"]');
  await page.click('#sLib');
  await page.waitForSelector('#lQ');
  await page.fill('#lQ', 'prusament azure');
  await page.waitForSelector('[data-use="prusament-pla-azure-blue"]');
  await page.click('[data-use="prusament-pla-azure-blue"]');
  await page.waitForSelector('#sSave');
  check((await page.inputValue('#sName')) === 'Prusament PLA Azure Blue', 'library pick fills the slot editor');
  await page.check('#sWrite');
  await clearReqs();
  await page.click('#sSave');
  await page.waitForFunction(() => document.querySelector('[data-slot="3"]').textContent.includes('Azure'));
  await page.waitForTimeout(300);
  r = await reqs();
  check(r.some((x) => x.json?.script?.startsWith("SET_PRINT_FILAMENT_CONFIG CONFIG_EXTRUDER=3 FILAMENT_TYPE='PLA'")), 'slot written to printer with SET_PRINT_FILAMENT_CONFIG');
  check(await page.evaluate(() => JSON.parse(localStorage.getItem('u1.slots'))[3].name === 'Prusament PLA Azure Blue'), 'slots persisted');
  await page.screenshot({ path: join(shots, 'printer-tab.png'), fullPage: true });

  // ---- print configuration from a local G-code file -------------------------------------------------------------
  await page.setInputFiles('#pLocalFile', gcodePath);
  await page.waitForSelector('#pcStart');
  const cfg = await text('#pDialog');
  check(cfg.includes('Select a Plate to Print') && cfg.includes('Confirm Printer') && cfg.includes('Configure Filaments') && cfg.includes('Print Preferences'), 'print screen has all four sections');
  check(cfg.includes('PLA | 3.6g') && cfg.includes('PETG | 9g'), 'per-filament chips "PLA | 3.6g", "PETG | 9g"');
  check(cfg.includes('34m') && cfg.includes('0.4 mm') && cfg.includes('12.6g'), 'plate shows time, nozzle, total grams');
  check(cfg.includes('U1-mock') && cfg.includes('online'), 'printer name + online');
  check(await page.isChecked('#pfLevel') && !(await page.isChecked('#pfFlow')), 'preferences default from print_task_config');
  await page.selectOption('[data-card="0"]', '2'); // PLA (T0) → tool head 3
  await page.check('#pfFlow');
  check((await text('#pcPrefG')) === 'SET_PRINT_PREFERENCES BED_LEVEL=1 FLOW_CALIBRATE=1 TIME_LAPSE_CAMERA=0', 'preference G-code preview');
  await page.screenshot({ path: join(shots, 'print-config.png'), fullPage: false });

  await clearReqs();
  await page.click('#pcStart');
  await page.waitForSelector('#pConfirm[open]');
  await page.click('#pConfirmNo');
  await page.waitForTimeout(300);
  r = await reqs();
  check(!r.some((x) => x.method === 'POST'), 'cancelling the confirm sends nothing');

  await page.click('#pcStart');
  await page.waitForSelector('#pConfirm[open]');
  await page.click('#pConfirmYes');
  await page.waitForFunction(() => /PRINTING|STARTING/.test(document.getElementById('pBadge').textContent), null, { timeout: 15000 });
  r = await reqs();
  const posts = r.filter((x) => x.method === 'POST').map((x) => x.path);
  check(JSON.stringify(posts) === JSON.stringify(['/server/files/upload', '/printer/gcode/script', '/printer/print/start']), `start order: upload → preferences → start (${posts.join(', ')})`);
  const up = r.find((x) => x.path === '/server/files/upload');
  check(up?.upload?.print === null && /^u1-e2e-\d+_\d+\.gcode$/.test(up?.upload?.filename ?? ''), 'upload has no print=true and a timestamped name');
  check(r.find((x) => x.path === '/printer/gcode/script')?.json?.script === 'SET_PRINT_PREFERENCES BED_LEVEL=1 FLOW_CALIBRATE=1 TIME_LAPSE_CAMERA=0', 'preferences sent');
  check(r.find((x) => x.path === '/printer/print/start')?.query?.filename === up?.upload?.filename, 'start uses the uploaded filename');
  check(r.every((x) => x.method === 'WS' || x.method === 'UPGRADE' ? true : x.apiKey === KEY), 'every HTTP request carried X-Api-Key');
  const uploaded = await fetch(`${mock.url}/server/files/gcodes/${up.upload.filename}`, { headers: { 'X-Api-Key': KEY } }).then((x) => x.text());
  const lines = uploaded.split('\n');
  check(lines.includes('T2') && lines.includes('T1') && !lines.includes('T0'), 'G-code remapped: T0 → T2, T1 kept');
  check(lines.includes('SM_PRINT_AUTO_FEED EXTRUDER=2') && lines.includes('M104 S220 T2'), 'SM_/M104 parameters remapped too');

  await page.waitForFunction(() => document.getElementById('pBadge').textContent === 'PRINTING', null, { timeout: 10000 });
  await page.waitForFunction(() => /\d+%/.test(document.getElementById('pKv').textContent) && !document.getElementById('pKv').textContent.startsWith('0%'), null, { timeout: 10000 });
  const kv = await text('#pKv');
  check(/\d+ \/ 50/.test(kv), `layer x / 50 shown (${kv})`);
  check(/remaining/.test(kv) && !/— remaining/.test(kv), 'remaining time shown');
  check((await page.title()).startsWith('Printing'), 'tab title shows progress');
  await page.screenshot({ path: join(shots, 'printing.png'), fullPage: true });

  // ---- pause / resume / stop, each confirmed -----------------------------------------------------------------------
  for (const [btn, state] of [['#pPause', 'PAUSED'], ['#pResume', 'PRINTING'], ['#pCancel', 'CANCELLED']]) {
    await page.click(btn);
    await page.waitForSelector('#pConfirm[open]');
    await page.click('#pConfirmYes');
    await page.waitForFunction((s) => document.getElementById('pBadge').textContent === s, state, { timeout: 10000 });
    check(true, `${btn.slice(2)} → ${state}`);
  }
  check((await text('#toasts')).includes('Print stopped'), 'state transition toast (PrintFailed)');
  check((await mockState()).state.print_stats.state === 'cancelled', 'mock print cancelled');

  // ---- upload only never starts ------------------------------------------------------------------------------------
  await clearReqs();
  await page.setInputFiles('#pLocalFile', gcodePath);
  await page.waitForSelector('#pcUpload');
  await page.click('#pcUpload');
  await page.waitForFunction(() => document.getElementById('pcStatus').textContent.startsWith('Uploaded as'));
  r = await reqs();
  check(r.some((x) => x.path === '/server/files/upload') && !r.some((x) => x.path === '/printer/print/start' || x.path === '/printer/gcode/script'), 'Upload only: upload, no preferences, no start');
  await page.keyboard.press('Escape');

  // ---- printer file list → start an existing file (confirmed) ---------------------------------------------------------
  await page.click('#pRefreshFiles');
  await page.waitForSelector('[data-remote="0"]');
  await page.click('[data-remote="0"]');
  await page.waitForSelector('#pcStart:not([disabled])');
  check(!(await page.$('#pcUpload')), 'printer-side file: no upload button');
  await clearReqs();
  await page.click('#pcStart');
  await page.click('#pConfirmYes');
  await page.waitForFunction(() => /PRINTING|STARTING/.test(document.getElementById('pBadge').textContent), null, { timeout: 10000 });
  r = await reqs();
  check(JSON.stringify(r.filter((x) => x.method === 'POST').map((x) => x.path)) === JSON.stringify(['/printer/gcode/script', '/printer/print/start']), 'printer-side file: preferences → start, no upload');
  await page.waitForFunction(() => document.getElementById('pBadge').textContent === 'PRINTING', null, { timeout: 10000 })
    .catch(async (e) => { console.log('badge:', await text('#pBadge'), 'mock:', (await mockState()).state.print_stats); throw e; });
  await page.click('#pCancel');
  await page.click('#pConfirmYes');
  await page.waitForFunction(() => document.getElementById('pBadge').textContent === 'CANCELLED', null, { timeout: 10000 })
    .catch(async (e) => { console.log('badge:', await text('#pBadge'), await text('#pCtlStatus'), 'mock:', (await mockState()).state.print_stats, (await reqs()).slice(-5)); throw e; });

  // ---- polling fallback (no websocket) ----------------------------------------------------------------------------------
  await page.click('#pConnect'); // disconnect
  await page.fill('#pUrl', noWs.url.replace('http://', ''));
  await page.fill('#pKey', '');
  await page.click('#pConnect');
  await page.waitForFunction(() => document.querySelector('#pMode span').textContent === 'polling', null, { timeout: 15000 });
  await page.waitForFunction(() => document.getElementById('pBadge').textContent === 'STANDBY', null, { timeout: 10000 });
  check(true, 'no websocket → polling, status still live');

  // ---- slicer → printer hand-off -------------------------------------------------------------------------------------------
  if (model) {
    await page.click('#pConnect');
    await page.fill('#pUrl', mock.url.replace('http://', ''));
    await page.fill('#pKey', KEY);
    await page.click('#pConnect');
    await page.waitForFunction(() => document.getElementById('pBadge').textContent === 'CANCELLED', null, { timeout: 15000 });
    await page.click('#appTabSlicer');
    await page.waitForFunction(() => document.getElementById('modelStatus').textContent.startsWith('Engine ready'), null, { timeout: 120000 });
    await page.setInputFiles('#file', model);
    await page.waitForFunction(() => !document.getElementById('slice').disabled, null, { timeout: 300000 });
    await page.click('#slice');
    await page.waitForFunction(() => document.getElementById('sliceStatus').textContent.startsWith('Sliced in'), null, { timeout: 900000 });
    await page.click('#printSliced');
    await page.waitForSelector('#pcStart:not([disabled])');
    check((await text('#pDialog')).includes('PLA |'), 'sliced model: filament chip shown');
    await clearReqs();
    await page.click('#pcStart');
    await page.click('#pConfirmYes');
    await page.waitForFunction(() => /PRINTING|STARTING/.test(document.getElementById('pBadge').textContent), null, { timeout: 30000 });
    r = await reqs();
    const upm = r.find((x) => x.path === '/server/files/upload');
    const body = await fetch(`${mock.url}/server/files/gcodes/${upm.upload.filename}`, { headers: { 'X-Api-Key': KEY } }).then((x) => x.text());
    check(/^PRINT_START/m.test(body) && /^T0$/m.test(body), `sliced G-code uploaded and started (${upm.upload.filename}, ${(body.length / 2 ** 20).toFixed(1)} MB)`);
    await page.screenshot({ path: join(shots, 'sliced-print.png'), fullPage: true });
  }

  check(errors.length === 0, `no page errors (${errors.join(' | ')})`);
} finally {
  await browser.close();
  server.kill();
  await mock.close(); await strict.close(); await noWs.close();
}
console.log(failures ? `${failures} check(s) failed` : 'all printer e2e checks passed');
process.exit(failures ? 1 : 0);
